export type Direction = "outbound" | "return";

export type RouteConfidence = "verified" | "partial";

export type RouteDirection = {
  /** Ordered stop names exactly as supplied by the route owner. */
  stops: string[];
  /** True when this direction was derived from the opposite direction. */
  derived: boolean;
  /** "partial" means at least part of the direction is inferred and needs owner confirmation. */
  confidence: RouteConfidence;
  /** Roads or instructions that are not stops. */
  via?: string[];
  /** Human-readable explanation for drivers and documentation. */
  note?: string;
};

export type TempuRoute = {
  number: string;
  name: string;
  outbound: RouteDirection;
  return: RouteDirection;
};

function samePath(stops: string[]): RouteDirection {
  return {
    stops: [...stops].reverse(),
    derived: true,
    confidence: "verified",
    note: "একই পথে — বিপরীত ক্রমে ফিরতি পথ",
  };
}

function explicit(stops: string[]): RouteDirection {
  return {
    stops,
    derived: false,
    confidence: "verified",
  };
}

function route(
  number: string,
  name: string,
  outboundStops: string[],
  returnDirection: RouteDirection
): TempuRoute {
  return {
    number,
    name,
    outbound: explicit(outboundStops),
    return: returnDirection,
  };
}

